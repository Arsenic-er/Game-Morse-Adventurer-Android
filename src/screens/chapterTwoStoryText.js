const IDS = ["paper", "margin", "call", "answer", "log"];
const ASSETS = ["scene", "scene", "illustration", "portrait", "scene"];
export const CHAPTER_TWO_LANGUAGES = Object.freeze(Object.keys(COPY));

export function chapterTwoStoryText(language) {
  const t = COPY[language] ?? COPY.en;
  return { ...t, beats: t.beats.map(([title, ...paragraphs], index) => ({
    id: IDS[index], asset: ASSETS[index], title, paragraphs, eyebrow: t.chapter,
  })) };
}
